CREATE TABLE vp_upload (
 id CHAR(36) PRIMARY KEY, video CHAR(36) NOT NULL UNIQUE, filename VARCHAR(255) NOT NULL,
 bytes BIGINT NOT NULL, hashes JSON NOT NULL, complete BOOLEAN NOT NULL DEFAULT FALSE,
 cleaned BOOLEAN NOT NULL DEFAULT FALSE, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE vp_part (
 upload_id CHAR(36) NOT NULL, part_no INT NOT NULL,
 PRIMARY KEY(upload_id,part_no), FOREIGN KEY(upload_id) REFERENCES vp_upload(id) ON DELETE CASCADE
);
